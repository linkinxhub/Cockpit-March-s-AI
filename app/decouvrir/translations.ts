export function discoveryText(text: string, language: Lang): string {
  if (language === "fr") return text;
  const translated = discoveryTranslations[text.trim()]?.[{ en: 0, de: 1, nl: 2 }[language]];
  return translated === undefined ? text : text.replace(text.trim(), translated);
}
