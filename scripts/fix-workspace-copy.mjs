import fs from 'node:fs';
const path='app/page.tsx';
let s=fs.readFileSync(path,'utf8');
const before=`                  <p>\n                    Ces valeurs restent enregistrées uniquement dans ce\n                    navigateur.\n                  </p>`;
const after=`                  <p>\n                    Ces valeurs sont synchronisées avec votre compte Web et mobile via le stockage Neon sécurisé.\n                  </p>`;
if(!s.includes(before)) throw new Error('Expected obsolete profile copy not found');
s=s.replace(before,after);
if(s.includes('Ces valeurs restent enregistrées uniquement dans ce')) throw new Error('Obsolete profile copy still present');
fs.writeFileSync(path,s);
console.log('Updated workspace synchronization copy.');
